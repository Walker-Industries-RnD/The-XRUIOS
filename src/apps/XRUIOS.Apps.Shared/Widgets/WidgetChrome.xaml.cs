using System;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;

namespace XRUIOS.Apps.Shared.Widgets;

/// <summary>
/// Draggable borderless card. The host wires <see cref="OnDragStart"/> to a
/// Photino native-move so the whole widget follows the cursor while the drag
/// strip is held.
///
/// Pin toggles Photino's always-on-top. Close asks the host to hide the window
/// (widgets never fully exit; the tray reopens them).
/// </summary>
public partial class WidgetChrome : UserControl
{
    /// <summary>Raised when the user presses on the drag strip. Host starts a Photino window move.</summary>
    public event Action? DragStarted;
    /// <summary>Raised when pin toggled. Host flips Photino.TopMost.</summary>
    public event Action<bool>? PinToggled;
    /// <summary>Raised when close pressed. Host hides the window; tray reopens.</summary>
    public event Action? CloseRequested;

    private bool _pinned;

    public string Title
    {
        get => TitleText.Text;
        set => TitleText.Text = value;
    }

    /// <summary>
    /// The chrome's body slot. Consumers set it in XAML via
    /// &lt;w:WidgetChrome.Body&gt;...&lt;/w:WidgetChrome.Body&gt; or in code as
    /// <c>widget.Body = someElement</c>. Backed by the inner BodyPresenter
    /// declared in WidgetChrome.xaml.
    /// </summary>
    public object? Body
    {
        get => BodyPresenter.Content;
        set => BodyPresenter.Content = value;
    }

    public WidgetChrome()
    {
        // InitializeComponent() is generated by the OpenSilver XAML compiler from
        // WidgetChrome.xaml (see <Page Include=... /> in the csproj).
        InitializeComponent();
        DragStrip.MouseLeftButtonDown += (_, _) => DragStarted?.Invoke();
        PinButton.Click += (_, _) => { _pinned = !_pinned; PinToggled?.Invoke(_pinned); };
        CloseButton.Click += (_, _) => CloseRequested?.Invoke();
    }
}
